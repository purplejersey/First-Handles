import json, sys
# usage: genrig.py <rig.json> <out puppetRig.js>
SRC = sys.argv[1] if len(sys.argv) > 1 else 'out/rig.json'
DST = sys.argv[2] if len(sys.argv) > 2 else '../../js/components/puppetRig.js'
d=json.load(open(SRC))
b=d['body']; J=b['joints']
L=["// Generated by the C2 cutting script from the stance illustration. Don't edit by hand:",
"// re-run the script if the art changes. Units are the drill box's 0-300 space.",
"// Each piece: size (w, h), top-left (x, y) relative to its pivot joint, and its",
"// rest angle (the bone's angle in the art, same convention as segAngle).","","export const PIECES = {"]
for k,v in d['pieces'].items(): L.append(f'  {k}: {{ w: {v["w"]}, h: {v["h"]}, x: {v["x"]}, y: {v["y"]}, rest: {v["rest"]} }},')
kneeT=round((J['knL'][1]-b['pelvisY'])/(b['ankleY']-b['pelvisY']),3)
L+=["};","","// Measurements taken from the art (pelvisY = pelvis height in the stance).",f"""export const ART_BODY = {{
  pelvisY: {b['pelvisY']}, neckTop: {b['neckTop']}, neckX: {J['neck'][0]},
  shoulderX: {b['shoulderX']}, shoulderY: {b['shoulderY']},
  upperArm: {b['upperArm']}, forearm: {b['forearm']},
  hipX: {b['hipX']}, hipDrop: 0, thigh: {b['thigh']}, shin: {b['shin']}, kneeT: {kneeT},
  ankleX: {b['ankleX']}, ankleY: {b['ankleY']},
}};""","",
"// Dribbling-hand thumb: base pivot and tip, relative to the wrist, in the art's (unrotated) hand frame.",
f"export const THUMB = {{ pivot: {b['thumb']['pivot']}, tip: {b['thumb']['tip']} }};","",
"// Recolor: the art's own fabric tones (mean luminance) under each mask, per piece.",
f"export const RECOLOR_REFS = {json.dumps(d.get('refs', {}))};"]
open(DST,'w').write("\n".join(L)+"\n")
